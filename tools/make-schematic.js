const T = (x, y, s, o = {}) => `<text x="${x}" y="${y}" font-size="${o.size || 13}" text-anchor="${o.anchor || 'start'}" font-weight="${o.bold ? 700 : 400}" fill="${o.fill || C.ink}">${s}</text>`;
const R = (x, y, w, h, o = {}) => `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${o.rx ?? 6}" fill="${o.fill || '#fff'}" stroke="${o.stroke || C.ink}" stroke-width="${o.sw || 2}"${o.dash ? ` stroke-dasharray="${o.dash}"` : ''}/>`;
const L = (pts, o = {}) => `<polyline points="${pts.map((p) => p.join(',')).join(' ')}" fill="none" stroke="${o.color || C.ink}" stroke-width="${o.sw || 2.5}" stroke-linejoin="round"${o.dash ? ` stroke-dasharray="${o.dash}"` : ''}/>`;
const dot = (x, y, c = C.ink) => `<circle cx="${x}" cy="${y}" r="4" fill="${c}"/>`;

// Земля вниз от точки (x,y)
const gnd = (x, y) => L([[x, y], [x, y + 10]]) + L([[x - 10, y + 10], [x + 10, y + 10]]) + L([[x - 6, y + 15], [x + 6, y + 15]]) + L([[x - 2, y + 20], [x + 2, y + 20]]);
// Сетевая метка: короткий отвод и подпись (dir = -1 влево, 1 вправо)
const net = (x, y, name, dir, color) => L([[x, y], [x + dir * 22, y]], { color }) + T(x + dir * 26, y + 4, name, { bold: true, anchor: dir > 0 ? 'start' : 'end', fill: color });
// Конденсатор вертикально между (x,y1) и (x,y2), подпись справа
const cap = (x, y1, y2, label, left) => {
  const m = (y1 + y2) / 2;
  return L([[x, y1], [x, m - 4]]) + L([[x - 12, m - 4], [x + 12, m - 4]]) + L([[x - 12, m + 4], [x + 12, m + 4]]) + L([[x, m + 4], [x, y2]]) +
    T(left ? x - 18 : x + 18, m + 4, label, { size: 12, anchor: left ? 'end' : 'start' });
};

// Корпус с выводами. left/right: [[имя, y], ...]. Возвращает {svg, p: {имя: {x, y, side}}}
function chip(x, y, w, h, title, sub, left, right, o = {}) {
  let s = R(x, y, w, h, { fill: o.fill || '#f4f6fb', sw: 2.5 });
  s += T(x + w / 2, y + 22, title, { anchor: 'middle', bold: true, size: 15 });
  if (sub) s += T(x + w / 2, y + 40, sub, { anchor: 'middle', size: 12, fill: C.mut });
  const p = {};
  (left || []).forEach(([n, py]) => { s += dot(x, py) + T(x + 10, py + 4, n, { size: 12.5 }); p[n] = { x, y: py }; });
  (right || []).forEach(([n, py]) => { s += dot(x + w, py) + T(x + w - 10, py + 4, n, { size: 12.5, anchor: 'end' }); p[n] = { x: x + w, y: py }; });
  return { svg: s, p };
}

